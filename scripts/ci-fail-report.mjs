// ci-fail-report.mjs — Debug channel for Actions log access without a local token.
//
// When a workflow step fails, this script posts the tail of a log file as a
// GitHub Issue (the repo's Issues API is public, so the report can be read
// without authentication). Idempotent: one issue per (workflow, commit).
//
// Env:
//   GITHUB_TOKEN   - required (workflow provides github.token; issues:write perm)
//   FAIL_LOG       - file to tail (default: eb.log)
//   MAX_LINES      - max log lines to embed (default: 300)
//   REPO           - owner/name (default: from GITHUB_REPOSITORY)
//
// Usage in a workflow step:
//   - name: Report failure as GitHub Issue (debug)
//     if: failure()
//     env:
//       GITHUB_TOKEN: ${{ github.token }}
//       FAIL_LOG: eb.log
//     run: node scripts/ci-fail-report.mjs
import fs from 'node:fs';

const token = process.env.GITHUB_TOKEN ?? '';
if (!token) {
  console.log('ci-fail-report: no GITHUB_TOKEN — skipping report');
  process.exit(0);
}

const repo = process.env.REPO ?? process.env.GITHUB_REPOSITORY ?? '';
if (!repo) {
  console.log('ci-fail-report: no GITHUB_REPOSITORY — skipping');
  process.exit(0);
}

const logFile = process.env.FAIL_LOG ?? 'eb.log';
const maxLines = Number(process.env.MAX_LINES ?? 300);
const log = fs.existsSync(logFile) ? fs.readFileSync(logFile, 'utf8') : '(no log file found)';
const lines = log.split(/\r?\n/);
const tail = lines.length > maxLines ? `... (${lines.length - maxLines} earlier lines truncated)\n` + lines.slice(-maxLines).join('\n') : log;

const sha = process.env.GITHUB_SHA ?? 'unknown';
const short = sha.slice(0, 7);
const title = `⚠️ [debug] Release build failure ${short}`;
const body = [
  `Auto-generated by the release workflow (run ${process.env.GITHUB_RUN_ID ?? ''}).`,
  ``,
  `Run: ${process.env.GITHUB_SERVER_URL ?? 'https://github.com'}/${repo}/actions/runs/${process.env.GITHUB_RUN_ID ?? ''}`,
  `Commit: ${sha}`,
  ``,
  'Tail of the failing step log:',
  '```',
  tail,
  '```',
  ``,
  '_Close this issue once the release build is fixed._',
].join('\n');

// Idempotency: skip if an open issue with the same title exists.
const search = await fetch(
  `https://api.github.com/search/issues?q=repo:${repo}+in:title+${encodeURIComponent(title)}+state:open&per_page=1`,
  { headers: { 'user-agent': 'ci-fail-report', authorization: `Bearer ${token}` } },
);
if (search.ok) {
  const s = JSON.parse(await search.text());
  if ((s.total_count ?? 0) > 0) {
    console.log('ci-fail-report: report already exists — skipping');
    process.exit(0);
  }
}

const r = await fetch(`https://api.github.com/repos/${repo}/issues`, {
  method: 'POST',
  headers: { 'user-agent': 'ci-fail-report', authorization: `Bearer ${token}`, 'content-type': 'application/json' },
  body: JSON.stringify({ title, body }),
});
if (r.ok) {
  const issue = JSON.parse(await r.text());
  console.log(`ci-fail-report: created issue #${issue.number} (${issue.html_url})`);
} else {
  console.log(`ci-fail-report: FAILED to create issue: HTTP ${r.status} ${await r.text()}`);
  // Non-zero so the (already failing) run stays visibly red at this step.
  process.exit(1);
}
